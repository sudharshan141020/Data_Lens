import { describe, it, expect } from 'vitest';
import { buildFindingsText } from './findingsText';

function session(v2, kpis) {
  return { fileName: 'sales.csv', result: { v2, kpis } };
}

describe('buildFindingsText', () => {
  it('returns an empty string when there is no analysis yet', () => {
    expect(buildFindingsText({ fileName: 'x.csv', result: null })).toBe('');
    expect(buildFindingsText({ fileName: 'x.csv', result: {} })).toBe('');
  });

  it('starts with the file name and a domain / row-count line, and ends with the no-AI footer', () => {
    const text = buildFindingsText(session({ profile: { domain: 'sales', row_count: 1200 } }));
    const lines = text.split('\n');
    expect(lines[0]).toBe('DataLens Summary — sales.csv');
    expect(lines[1]).toMatch(/^sales · 1,200 rows · /);
    expect(lines.at(-1)).toBe('Generated by DataLens · rule-based, no AI calls · nothing stored');
  });

  describe('key metrics', () => {
    const kpis = {
      row_count: 1200, column_count: 9, data_completeness_pct: 99, date_range: 'x', // all blacklisted
      total_revenue: 12345.678,
      profit_margin_pct: 12.345,
      order_count: 1234,
      segment: 'Consumer',
    };

    it('drops the housekeeping keys and formats currency, percent, plain numbers and strings', () => {
      const text = buildFindingsText(session({ profile: {} }, kpis));
      expect(text).toContain('KEY METRICS');
      expect(text).toContain('• Total Revenue: $12,345.68');
      expect(text).toContain('• Profit Margin: 12.3%');
      expect(text).toContain('• Order Count: 1,234');
      expect(text).toContain('• Segment: Consumer');
      expect(text).not.toMatch(/Row Count|Column Count|Completeness|Date Range/);
    });

    it('shows at most 6 metrics', () => {
      const many = Object.fromEntries(Array.from({ length: 10 }, (_, i) => [`metric_${i}`, i]));
      const bullets = buildFindingsText(session({ profile: {} }, many)).split('\n').filter((l) => l.startsWith('• '));
      expect(bullets).toHaveLength(6);
    });

    it('omits the section entirely when there are no usable metrics', () => {
      expect(buildFindingsText(session({ profile: {} }, { row_count: 5 }))).not.toContain('KEY METRICS');
    });
  });

  it('lists the top 5 findings by score, numbered', () => {
    const findings = Array.from({ length: 7 }, (_, i) => ({ text: `finding ${i}`, score: i }));
    const text = buildFindingsText(session({ profile: {}, findings }));
    expect(text).toContain('1. finding 6');
    expect(text).toContain('5. finding 2');
    expect(text).not.toContain('finding 1');
  });

  it('includes the story beats in order', () => {
    const text = buildFindingsText(session({ profile: {}, story: [{ label: 'First', text: 'a' }, { label: 'Second', text: 'b' }] }));
    expect(text.indexOf('First: a')).toBeLessThan(text.indexOf('Second: b'));
  });

  it('summarises the largest segment without its "Segment N:" prefix', () => {
    const segments = { available: true, k: 3, clusters: [
      { label: 'Segment 1: Small spenders', pct: 20 },
      { label: 'Segment 2: Big spenders', pct: 55 },
      { label: 'Segment 3: Mid spenders', pct: 25 },
    ] };
    expect(buildFindingsText(session({ profile: {}, segments }))).toContain('SEGMENTS: 3 natural groups found — largest is "Big spenders" at 55%.');
  });

  it('includes seasonality only when available', () => {
    expect(buildFindingsText(session({ profile: {}, seasonality: { available: true, summary: 'Peaks in December.' } }))).toContain('SEASONALITY: Peaks in December.');
    expect(buildFindingsText(session({ profile: {}, seasonality: { available: false, summary: 'x' } }))).not.toContain('SEASONALITY');
  });

  it('flags only HIGH priority weak points (max 2) with their suggested action', () => {
    const weak_points = [
      { problem: 'High one', priority: 'high', suggested_action: 'Fix it' },
      { problem: 'Medium one', priority: 'medium', suggested_action: 'Meh' },
      { problem: 'High two', priority: 'high' },
      { problem: 'High three', priority: 'high', suggested_action: 'Too many' },
    ];
    const text = buildFindingsText(session({ profile: {}, weak_points }));
    expect(text).toContain('⚠ High one');
    expect(text).toContain('   → Fix it');
    expect(text).toContain('⚠ High two');
    expect(text).not.toContain('Medium one');
    expect(text).not.toContain('High three');
  });

  it('rounds the data quality score', () => {
    expect(buildFindingsText(session({ profile: {}, data_quality: { overall_quality_score: 87.6 } }))).toContain('Data quality: 88/100');
  });

  describe('why it changed', () => {
    const drivers = (headline) => ({ available: true, comparisons: [{ id: 'latest_month', headline }] });

    it('adds the driver headline for the latest move', () => {
      const text = buildFindingsText(session({ profile: {}, drivers: drivers('Sales fell 20%: 100% of the drop is Category=Furniture.') }));
      expect(text).toContain('WHY IT CHANGED: Sales fell 20%: 100% of the drop is Category=Furniture.');
    });

    it('is left out when drivers are unavailable or missing', () => {
      expect(buildFindingsText(session({ profile: {}, drivers: { available: false, comparisons: [] } }))).not.toContain('WHY IT CHANGED');
      expect(buildFindingsText(session({ profile: {} }))).not.toContain('WHY IT CHANGED');
    });
  });

  describe('robustness', () => {
    const rob = (verdict, headline) => ({ available: true, overall: { verdict, headline } });

    it('adds a line only when the result depends on a few rows', () => {
      const text = buildFindingsText(session({ profile: {}, robustness: rob('sensitive', 'Sensitive to extreme rows: 1 of 4 headline numbers move materially without them.') }));
      expect(text).toContain('ROBUSTNESS: Sensitive to extreme rows: 1 of 4 headline numbers move materially without them.');
    });

    it('stays quiet for a robust result, an unavailable one, or none at all', () => {
      expect(buildFindingsText(session({ profile: {}, robustness: rob('robust', 'All hold.') }))).not.toContain('ROBUSTNESS');
      expect(buildFindingsText(session({ profile: {}, robustness: { available: false } }))).not.toContain('ROBUSTNESS');
      expect(buildFindingsText(session({ profile: {} }))).not.toContain('ROBUSTNESS');
    });
  });
});
